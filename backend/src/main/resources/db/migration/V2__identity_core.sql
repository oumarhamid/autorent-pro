CREATE TABLE identity_users (
    id UUID PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(32) NOT NULL,
    failed_login_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP(6) WITH TIME ZONE,
    last_login_at TIMESTAMP(6) WITH TIME ZONE,
    password_changed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_identity_users_email
        UNIQUE (email),

    CONSTRAINT chk_identity_users_email_normalized
        CHECK (email = LOWER(BTRIM(email))),

    CONSTRAINT chk_identity_users_status
        CHECK (status IN ('ACTIVE', 'DISABLED')),

    CONSTRAINT chk_identity_users_failed_login_attempts
        CHECK (failed_login_attempts >= 0)
);

CREATE INDEX idx_identity_users_status
    ON identity_users(status);


CREATE TABLE identity_roles (
    id UUID PRIMARY KEY,
    code VARCHAR(64) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_identity_roles_code
        UNIQUE (code)
);


CREATE TABLE identity_permissions (
    id UUID PRIMARY KEY,
    code VARCHAR(96) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT uk_identity_permissions_code
        UNIQUE (code)
);


CREATE TABLE identity_user_roles (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    role_id UUID NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_identity_user_roles_user
        FOREIGN KEY (user_id)
        REFERENCES identity_users(id),

    CONSTRAINT fk_identity_user_roles_role
        FOREIGN KEY (role_id)
        REFERENCES identity_roles(id),

    CONSTRAINT uk_identity_user_roles_user_role
        UNIQUE (user_id, role_id)
);

CREATE INDEX idx_identity_user_roles_role_id
    ON identity_user_roles(role_id);


CREATE TABLE identity_role_permissions (
    id UUID PRIMARY KEY,
    role_id UUID NOT NULL,
    permission_id UUID NOT NULL,
    scope VARCHAR(16) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_identity_role_permissions_role
        FOREIGN KEY (role_id)
        REFERENCES identity_roles(id),

    CONSTRAINT fk_identity_role_permissions_permission
        FOREIGN KEY (permission_id)
        REFERENCES identity_permissions(id),

    CONSTRAINT chk_identity_role_permissions_scope
        CHECK (scope IN ('GLOBAL', 'AGENCY', 'SELF')),

    CONSTRAINT uk_identity_role_permissions_role_permission_scope
        UNIQUE (role_id, permission_id, scope)
);

CREATE INDEX idx_identity_role_permissions_permission_id
    ON identity_role_permissions(permission_id);


